// 未知状态的兜底定义，避免渲染时抛错
const STATUS_FALLBACK = { name: '未知状态', icon: '❔', good: true, sign: '', desc: '（该状态尚未登记说明）' };

// 取状态定义；未登记的键回退到兜底定义（名字仍用键名，便于定位漏登记）
function getStatusDef(key) {
  return STATUS_DEFS[key] || Object.assign({}, STATUS_FALLBACK, { name: key });
}
