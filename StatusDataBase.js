// ============================================================
//  杀戮奶蛙 · 状态数据库（增益 / 减益）
// ============================================================
//  本文件是**纯数据**，不含任何 DOM 操作：
//    · 不引用 document / window
//    · 不依赖任何游戏逻辑（不引用 S / CARD_DB / 敌人数据）
//  因此可以独立增删与复用。
//
//  状态的「渲染」（徽章、悬浮窗）在 RenderManager.js；
//  状态的「来源」（谁在什么时候挂上它）在 GameManager.js。
//
//  为什么要这样切：
//    数据文件只描述"状态是什么"，渲染文件负责"怎么画"，
//    规则文件负责"何时生效"。三者互不越界，改文案不必碰渲染，
//    改样式不必碰数据。
//
//  ---- 通用性（重要）----
//  这里登记的状态对「敌我双方」一律通用，不存在只能挂在某一方的状态。
//  谁都可以获得任意状态，结算逻辑也一视同仁地读取持有者自己的状态：
//    · 力量        —— 谁的攻击都吃自己的力量加成
//    · 肚皮鼓胀    —— 谁获得格挡都吃自己的额外格挡
//    · 眩晕        —— 谁被眩晕谁跳过回合
//    · 狂笑不止 / 笑点爆炸 —— 依赖「狂笑值」这个资源；
//                    没有狂笑值的单位（目前是敌人）即使挂上也不会触发，
//                    这是资源差异，不是"仅某一方可用"的限制
//
//  状态的执有容器也统一：玩家在 S.states，敌人在 S.enemy.states，
//  两者结构完全一致（均为 { 状态键: 数值 }），由 StatusManager.js 的
//  statusValue / addStatus 统一读写。
//
//  ---- 关于 good ----
//  good 表示该状态对「持有者自身」是有利还是不利，**不是相对玩家而言**。
//    例：力量提升的是持有者的攻击力，所以无论它挂在敌人还是奶蛙身上，
//    对持有者都是正面效果，应当显示为增益（绿色）。
//
//  ---- 字段说明 ----
//    name  状态中文名
//    icon  徽章与悬浮窗上显示的图标
//    good  true = 正面效果（绿） / false = 负面效果（红）
//    sign  数值前缀，如 '+'；无层数状态留空
//    desc  完整说明，悬浮窗正文
//
//  数值口径：条目里的「数值」指的是徽章上显示的层数/强度，
//  具体含义由 desc 解释，避免界面与说明两处各写一套。
// ============================================================

